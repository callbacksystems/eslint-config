// The rule reference is generated, never written by hand: every column comes
// from something that already exists and is the only copy of itself. Add a rule,
// reword a description, move one between presets, and the table follows.
//
// The prose does not live here. Each row links to the rule's source, where the
// header comment explaining it already is.

import assert from "node:assert/strict"
import { readFile, writeFile } from "node:fs/promises"
import path from "node:path"
import url from "node:url"
import plugin from "#rules"
import browser from "#browser"
import rails from "#rails"
import turbo from "#turbo"
import { callbacksystemsRules } from "#internal/base-rules/callbacksystems"
import { stimulusRules } from "#internal/stimulus-rules"

const HERE = path.dirname(url.fileURLToPath(import.meta.url))
const DOC_PATH = path.join(HERE, "..", "docs", "README.md")
const PRESETS = [
  [ "/base", Object.keys(callbacksystemsRules) ],
  [ "/browser", enabledIn(browser) ],
  [ "/rails", enabledIn(rails) ],
  [ "/stimulus", Object.keys(stimulusRules) ],
  [ "/turbo", enabledIn(turbo) ]
]
const HEADING = `# Rules

<!-- Generated by \`npm run test:update-snapshots\`. Do not edit by hand. -->

A rule's namespace is the preset that turns it on: \`stimulus/...\` comes with
\`/stimulus\`, \`browser/...\` with \`/browser\`, and so on. A rule with no namespace
comes with \`/base\`.

Each rule links to its source, where a header comment explains what it is for and
why it exists.
`

export async function matchRulesDocument() {
  const actual = documentText()

  await (process.env.UPDATE_SNAPSHOTS
    ? writeFile(DOC_PATH, actual)
    : compareToCommitted(actual))
}

// The claim the reference makes in prose, kept true by a test rather than by
// remembering: a rule placed outside the preset its namespace names would make
// the sentence above a lie, silently.
export function rulesMisfiledByNamespace() {
  return ruleIds().filter((id) => presetsFor(id).join(", ") !== presetOfNamespace(id))
}

function enabledIn(preset) {
  return preset.flatMap((block) => Object.keys(block.rules ?? {}))
}

function documentText() {
  return `${HEADING}\n${table()}`
}

function table() {
  return `${[ "| Rule | Preset | Fix | Description |", "|---|---|---|---|", ...rows() ].join("\n")}\n`
}

function rows() {
  return ruleIds().map((id) => rowFor(id))
}

function ruleIds() {
  return Object.keys(plugin.rules)
}

function rowFor(id) {
  const { meta } = plugin.rules[id]
  const link = `[\`${id}\`](../src/rules/${id}.js)`
  return `| ${link} | \`${presetsFor(id).join("`, `")}\` | ${meta.fixable ? "yes" : ""} | ${meta.docs.description} |`
}

function presetsFor(id) {
  return PRESETS.filter(([ , ids ]) => ids.includes(`callbacksystems/${id}`)).map(([ name ]) => name)
}

async function compareToCommitted(actual) {
  const expected = await readFile(DOC_PATH, "utf8").catch(() => null)
  const hint = "docs/README.md is out of date. Run `npm run test:update-snapshots`."
  assert.equal(actual, expected, hint)
}

function presetOfNamespace(id) {
  return id.includes("/") ? `/${id.split("/")[0]}` : "/base"
}
